#!/usr/bin/env node
/**
 * tools/build.mjs —— 唯一构建入口（esbuild，纯 node，零额外依赖）。
 *
 * 产出（只写 lib/，不写 output/、不写工作区别处）：
 *   src/host/index.ts   -> lib/index.js    ESM / platform=node / external: @deepseek-ai/*、node 内建
 *   src/client/index.ts -> lib/client.js   CJS 代码体 + window.__ModuleLoader__.load 包装
 *
 * 客户端包装的精确形状（04 §7.3）：
 *   window.__ModuleLoader__.load({
 *     id: "<package.json 的 name>",
 *     factory: function (require) { var module = { exports: {} }; var exports = module.exports; <bundle>; return module.exports; }
 *   });
 * 工厂形参必须叫 `require`：A02-3 的判据是 `grep -c 'require("react")' lib/client.js` ≥ 1，
 * 而宿主平台表的 React 只能经由这个形参取到。
 *
 * 确定性：不写时间戳 / 不写随机量 / 不写绝对路径；本脚本每次构建都会**构建两次并逐字节比对**，
 * 不一致即退 1（A60-1 的前置保证）。
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import esbuild from 'esbuild'
import { hostShapeFailures } from './host-shape.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const LIB = join(ROOT, 'lib')
const VERSION_FILE = join(ROOT, 'src', 'shared', 'version.ts')

/** 与宿主约定好的三项一致 id：package.json name / cordis.patch.yml 行 id / client 模块 id */
const HOST_EXTERNAL = ['@deepseek-ai/*', 'node:*']
const CLIENT_EXTERNAL = [
  'react',
  'react-dom',
  'react-dom/client',
  'react/jsx-runtime',
  'react/jsx-dev-runtime',
  '@deepseek-ai/*',
]

/** 两次构建共用的固定选项：任何一项变化都等于换了构建语义，别悄悄改。 */
const COMMON = {
  absWorkingDir: ROOT,
  bundle: true,
  write: false,
  charset: 'utf8',
  target: 'es2022',
  sourcemap: false,
  legalComments: 'none',
  logLevel: 'warning',
  minify: false,
}

function fail(message) {
  console.error(`build: FAIL — ${message}`)
  process.exit(1)
}

function normalize(text) {
  const body = text.replace(/\r\n/g, '\n').trimEnd()
  return body === '' ? '' : `${body}\n`
}

/** 绝对路径进产物 = 换台机器 sha 就变，直接判失败。 */
function assertNoAbsolutePath(label, text) {
  const variants = [ROOT, ROOT.replaceAll('\\', '/'), ROOT.replaceAll('/', '\\')]
  for (const variant of variants) {
    if (text.includes(variant)) fail(`${label}: 产物里出现绝对路径（破坏确定性）：${variant}`)
  }
}

/** 同一份源码构建两次必须逐字节相同——这是“构建确定”的唯一可信证据。 */
async function buildDeterministic(label, options) {
  const first = await esbuild.build({ ...COMMON, ...options })
  const second = await esbuild.build({ ...COMMON, ...options })
  const a = first.outputFiles.map((file) => file.text).join('')
  const b = second.outputFiles.map((file) => file.text).join('')
  if (a !== b) fail(`${label}: 同一输入两次构建输出不一致（存在非确定性）`)
  assertNoAbsolutePath(label, a)
  return { text: a, bytes: Buffer.byteLength(a, 'utf8') }
}

function wrapClientModule(bundleText) {
  const body = normalize(bundleText)
  if (body === '') fail('client: esbuild 产出为空')

  const wrapped = [
    '/* GENERATED by tools/build.mjs — do not edit. */',
    `window.__ModuleLoader__.load({ id: ${JSON.stringify(pkg.name)}, factory: function (require) {`,
    '\tvar module = { exports: {} };',
    '\tvar exports = module.exports;',
    body,
    '\treturn module.exports;',
    '} });',
    '',
  ].join('\n')

  return normalize(wrapped)
}

function assertClientShape(text) {
  const required = [
    ['window.__ModuleLoader__.load', '缺 ModuleLoader 包装'],
    ['factory: function (require)', '工厂形参必须命名 require'],
    ['require("react")', 'React 必须是 external（应出现 require("react")）'],
  ]
  for (const [needle, reason] of required) {
    if (!text.includes(needle)) fail(`client: ${reason}（找不到 ${needle}）`)
  }
  // 反向断言：React 一旦被打进来，通常带这些标记。
  for (const needle of ['react.production', '__SECRET_INTERNALS_DO_NOT_USE_OR_YOU_WILL_BE_FIRED', 'ReactCurrentOwner']) {
    if (text.includes(needle)) fail(`client: React 被打包进产物了（命中 ${needle}）`)
  }
}

function assertHostShape(text) {
  if (!/(^|\n)export\b/.test(text)) fail('host: 产物不是 ESM（找不到 export 语句）')
  if (!text.includes('dsh-plugin-control-your-development')) fail('host: 产物里没有插件 id')
  // fs 边界（1.2.0：只读白名单 + 写 API 黑名单，见 tools/host-shape.mjs 与 04 §9.5）。
  // 规则抽到独立模块，便于 tests/integration/host-shape.test.ts 正反两侧审计。
  for (const reason of hostShapeFailures(text)) fail(reason)
}

const pkg = JSON.parse(await readFile(join(ROOT, 'package.json'), 'utf8'))
const versionSource = await readFile(VERSION_FILE, 'utf8')
const versionMatch = /VERSION\s*=\s*'([^']+)'/.exec(versionSource)
if (!versionMatch) fail('找不到 src/shared/version.ts 的 VERSION 常量')
if (versionMatch[1] !== pkg.version) {
  fail(`版本不一致：src/shared/version.ts=${versionMatch[1]}，package.json=${pkg.version}`)
}

await mkdir(LIB, { recursive: true })

const host = await buildDeterministic('host', {
  entryPoints: ['src/host/index.ts'],
  outfile: 'lib/index.js',
  platform: 'node',
  format: 'esm',
  external: HOST_EXTERNAL,
})

const clientRaw = await buildDeterministic('client', {
  entryPoints: ['src/client/index.ts'],
  outfile: 'lib/client.tmp.js',
  platform: 'browser',
  format: 'cjs',
  external: CLIENT_EXTERNAL,
})

const clientText = wrapClientModule(clientRaw.text)
const hostText = normalize(host.text)

assertHostShape(hostText)
assertClientShape(clientText)

await writeFile(join(LIB, 'index.js'), hostText, 'utf8')
await writeFile(join(LIB, 'client.js'), clientText, 'utf8')

console.log(`threadline build — ${pkg.name} v${pkg.version}`)
console.log(`  version  src/shared/version.ts ↔ package.json 一致`)
console.log(`  host     src/host/index.ts   -> lib/index.js   ${Buffer.byteLength(hostText, 'utf8')} bytes  (esm, platform=node)`)
console.log(`  client   src/client/index.ts -> lib/client.js  ${Buffer.byteLength(clientText, 'utf8')} bytes  (cjs, __ModuleLoader__.load)`)
console.log(`  react    external（require("react") 存在；React 源码 0 字节）`)
console.log(`  determinism  两次构建逐字节一致`)
