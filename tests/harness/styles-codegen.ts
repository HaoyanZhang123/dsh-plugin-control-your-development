/*
 * styles-codegen.ts —— src/client/styles/*.css → styles/css.ts 的唯一转换实现。
 *
 * 谁用它：
 * - tests/harness/emit-styles.mjs（写盘 / --check）
 * - tests/ui-shell/styles.test.ts（内存里重算并逐字比对，漂移即红）
 *
 * 为什么要支持多文件（2026-11-04 Lead 集成决策）：
 * T07（星图/时间轴）与 T08（轮次带/检查器）并行开发，都需要伪类 / keyframes / 光标这类只能用 CSS 表达的规则。
 * 让两个任务同时往 base.css 追加会产生写冲突、破坏「单一事实源」。因此：
 *   每个界面区域一个 CSS 文件（map.css / timeline.css / turns.css / inspector.css …），
 *   注入路径仍然只有一条（styles/index.ts 的 installStyles 遍历本表），
 *   生成物仍然只有一份（css.ts），漂移仍由 styles.test.ts 逐字守。
 *
 * 顺序：tokens.css → base.css → 其余按文件名字母序（后加载者靠选择器特异性竞争，不靠顺序）。
 * 这里不 import 任何 @deepseek-ai 客户端包；只依赖 node:fs / node:path。
 */
import { readFileSync, readdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

/** plugin/ 根目录（本文件在 plugin/tests/harness/ 下）。 */
export const PLUGIN_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
export const STYLES_DIR = join(PLUGIN_ROOT, 'src', 'client', 'styles')

/** 一个 CSS 源文件（唯一事实源的单元）。 */
export interface StyleSource {
  /** 文件名，如 tokens.css */
  name: string
  /** 注入时的去重键，如 threadline/turns.css */
  key: string
  /** 文件内容（逐字） */
  css: string
}

/** 读单个 .css 源文件（保留给老调用方）。 */
export function readStyleSource(name: string, root: string = STYLES_DIR): string {
  return readFileSync(join(root, name), 'utf8')
}

/** 排序：tokens 最先，base 第二，其余按文件名字母序。 */
function orderOf(name: string): number {
  if (name === 'tokens.css') return 0
  if (name === 'base.css') return 1
  return 2
}

/** 枚举 styles/ 下全部 .css（不硬编码文件名清单：加了文件自动纳入，漂移即红）。 */
export function listStyleSources(root: string = STYLES_DIR): StyleSource[] {
  const names = readdirSync(root)
    .filter((name) => name.endsWith('.css'))
    .sort((a, b) => orderOf(a) - orderOf(b) || a.localeCompare(b))
  return names.map((name) => ({
    name,
    key: 'threadline/' + name,
    css: readFileSync(join(root, name), 'utf8'),
  }))
}

/** 按注入键取一份 CSS；缺文件时返回空串（不抛，避免一个漏文件让整个面板空白）。 */
export function sheet(sources: StyleSource[], key: string): string {
  return sources.find((s) => s.key === key)?.css ?? ''
}

/**
 * 生成 css.ts 的完整文本。
 * 纯函数；用 JSON.stringify 转义，因此 CSS 里出现引号/反斜杠/换行都不会破；
 * 结果里没有反引号（工厂纪律：模板串事故）。
 */
export function renderStylesModule(sources: StyleSource[]): string {
  const NL = String.fromCharCode(10)
  const head = [
    '/*',
    ' * GENERATED by tests/harness/emit-styles.mjs — 禁止手改。',
    ' * 源：src/client/styles/*.css（唯一事实源；每个界面区域一个文件）。',
    ' * 这里只是把 CSS 转成可注入的普通字符串（不用模板串/反引号）。',
    ' */',
    '',
  ].join(NL)
  const items = sources
    .map((s) => '  { key: ' + JSON.stringify(s.key) + ', css: ' + JSON.stringify(s.css) + ' },')
    .join(NL)
  const body = [
    'export const STYLE_SHEETS: ReadonlyArray<{ key: string; css: string }> = [',
    items,
    ']',
    '',
    "export const TOKENS_CSS: string = STYLE_SHEETS.find((s) => s.key === 'threadline/tokens.css')?.css ?? ''",
    '',
    "export const BASE_CSS: string = STYLE_SHEETS.find((s) => s.key === 'threadline/base.css')?.css ?? ''",
    '',
    'export const THREADLINE_CSS: string = STYLE_SHEETS.map((s) => s.css).join(String.fromCharCode(10))',
    '',
  ].join(NL)
  return head + body
}

/** 从磁盘读全部源文件，生成模块文本。 */
export function buildStylesModule(root: string = STYLES_DIR): string {
  return renderStylesModule(listStyleSources(root))
}

/** 生成物路径。 */
export const CSS_MODULE_PATH = join(STYLES_DIR, 'css.ts')
